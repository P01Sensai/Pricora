function generate60DayHistory(basePrice: number) {
  const history = [];
  const now = Date.now();
  for (let i = 60; i >= 0; i--) {
    // Simulate festive price drop in last 10 days
    let price = basePrice;
    if (i > 15) {
      // Prior to festival: slightly higher price (between 5% to 15% higher)
      const inflation = 1 + (0.05 + Math.sin(i / 5) * 0.05);
      price = Math.round(basePrice * inflation);
    } else {
      // Festival sale: lowest dip
      const saleDip = 1 - (Math.sin((15 - i) / 5) * 0.04);
      price = Math.round(basePrice * saleDip);
    }
    history.push({
      id: 60 - i,
      listing_id: "hist",
      price: price * 100, // paise
      in_stock: true,
      recorded_at: new Date(now - i * 86400000).toISOString(),
    });
  }
  return history;
}

